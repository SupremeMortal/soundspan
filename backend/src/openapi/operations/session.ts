import { defineOperation } from "../defineOperation";
import { ApiError, standardErrors } from "../schemas/common";
import {
    ApiDocumentInfo,
    AuthConfig,
    HealthStatus,
    LoginRequest,
    LoginResponse,
    LoginUser,
    MessageResponse,
    OnboardingStatus,
    RefreshSessionRequest,
    SessionTokens,
    SystemFeatures,
} from "../schemas/session";

/** Connection and session operations. */
export const sessionOperations = [
    defineOperation({
        method: "get",
        path: "/api/health",
        operationId: "getHealth",
        tag: "session",
        summary: "Server health; 503 with the same payload when not ready",
        anonymous: true,
        responses: { 200: HealthStatus, 503: HealthStatus },
    }),
    defineOperation({
        method: "get",
        path: "/api/auth/config",
        operationId: "getAuthConfig",
        tag: "session",
        summary: "Sign-in methods the server offers",
        anonymous: true,
        responses: { 200: AuthConfig, 503: ApiError },
    }),
    defineOperation({
        method: "get",
        path: "/api/onboarding/status",
        operationId: "getOnboardingStatus",
        tag: "session",
        summary: "Whether the server or the signed-in user needs onboarding",
        anonymous: true,
        responses: { 200: OnboardingStatus, 500: ApiError, 503: ApiError },
    }),
    defineOperation({
        method: "post",
        path: "/api/auth/login",
        operationId: "login",
        tag: "session",
        summary: "Sign in with a username or email and password",
        description:
            "Answers a token response, or a second-factor challenge when the account has 2FA and `token` is absent. 403 when local login is disabled.",
        anonymous: true,
        body: LoginRequest,
        responses: {
            200: LoginResponse,
            400: ApiError,
            401: ApiError,
            403: ApiError,
            500: ApiError,
            503: ApiError,
        },
    }),
    defineOperation({
        method: "post",
        path: "/api/auth/refresh",
        operationId: "refreshSession",
        tag: "session",
        summary: "Exchange a refresh token for new access and refresh tokens",
        anonymous: true,
        body: RefreshSessionRequest,
        responses: {
            200: SessionTokens,
            400: ApiError,
            401: ApiError,
            429: ApiError,
            503: ApiError,
        },
    }),
    defineOperation({
        method: "post",
        path: "/api/auth/logout",
        operationId: "logout",
        tag: "session",
        summary: "Sign out; tokens are discarded by the client",
        anonymous: true,
        responses: { 200: MessageResponse, 503: ApiError },
    }),
    defineOperation({
        method: "get",
        path: "/api/auth/me",
        operationId: "getCurrentUser",
        tag: "session",
        summary: "The signed-in user",
        responses: { 200: LoginUser, 404: ApiError, ...standardErrors },
    }),
    defineOperation({
        method: "get",
        path: "/api/docs.json",
        operationId: "getApiDocument",
        tag: "session",
        summary: "The server's OpenAPI document; only info.version is declared",
        responses: { 200: ApiDocumentInfo, ...standardErrors },
    }),
    defineOperation({
        method: "get",
        path: "/api/system/features",
        operationId: "getSystemFeatures",
        tag: "session",
        summary: "Feature flags and detected capabilities",
        responses: { 200: SystemFeatures, ...standardErrors },
    }),
];
