/// Writes `lib/src/generated/anonymous_operations.g.dart` from the
/// client-surface spec: the operations sent without a credential and the
/// `operationId` of every operation, both keyed by `METHOD path-template`.
///
/// Run from the package root by `client/tool/gen.sh`, after the generator.
library;

import 'dart:convert';
import 'dart:io';

const _specPath = 'openapi/soundspan-client.json';
const _outputPath = 'lib/src/generated/anonymous_operations.g.dart';
const _methods = {'get', 'put', 'post', 'delete', 'options', 'head', 'patch'};

/// The keys of the operations whose effective security requirement is
/// empty: an operation's own `security`, or the root `security` when the
/// operation has none, is `[]` or contains the empty requirement `{}`.
///
/// An operation with no requirement at either level is not anonymous, so
/// a credential is sent when the spec says nothing.
Set<String> anonymousOperations(Map<String, Object?> spec) => {
  for (final (key, operation) in _operations(spec))
    if (_isAnonymous(operation['security'] ?? spec['security'])) key,
};

/// Every operation key mapped to its `operationId`.
Map<String, String> operationIds(Map<String, Object?> spec) => {
  for (final (key, operation) in _operations(spec))
    if (operation['operationId'] case final String id) key: id,
};

/// The Dart library holding [anonymousOperations] and [operationIds].
String renderOperations(Map<String, Object?> spec) {
  final anonymous = anonymousOperations(spec).toList()..sort();
  final ids = operationIds(spec);
  final keys = ids.keys.toList()..sort();
  return [
    '// Generated by tool/gen_anonymous_operations.dart. Do not edit.',
    '',
    '/// Operations the spec declares without a security requirement, as',
    '/// `METHOD path-template` keys.',
    'const Set<String> anonymousOperations = {',
    for (final key in anonymous) "  '$key',",
    '};',
    '',
    '/// The `operationId` of every operation, by `METHOD path-template` key.',
    'const Map<String, String> operationIds = {',
    for (final key in keys) "  '$key': '${ids[key]}',",
    '};',
    '',
  ].join('\n');
}

Iterable<(String, Map<String, Object?>)> _operations(
  Map<String, Object?> spec,
) sync* {
  final paths = spec['paths'];
  if (paths is! Map<String, Object?>) return;
  for (final MapEntry(key: path, value: item) in paths.entries) {
    if (item is! Map<String, Object?>) continue;
    for (final MapEntry(key: method, value: operation) in item.entries) {
      if (!_methods.contains(method) || operation is! Map<String, Object?>) {
        continue;
      }
      yield ('${method.toUpperCase()} $path', operation);
    }
  }
}

bool _isAnonymous(Object? security) =>
    security is List<Object?> &&
    (security.isEmpty ||
        security.any((r) => r is Map<Object?, Object?> && r.isEmpty));

void main() {
  final spec = jsonDecode(File(_specPath).readAsStringSync());
  File(_outputPath)
      .writeAsStringSync(renderOperations(spec as Map<String, Object?>));
}
