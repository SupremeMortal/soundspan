import 'package:soundspan_api/src/operations.dart';
import 'package:test/test.dart';

import '../tool/gen_anonymous_operations.dart';

const _spec = <String, Object?>{
  'openapi': '3.0.0',
  'paths': {
    '/api/health': {
      'get': {'operationId': 'getHealth', 'security': <Object?>[]},
    },
    '/api/auth/login': {
      'post': {
        'operationId': 'login',
        'security': [<String, Object?>{}],
      },
    },
    '/api/auth/me': {
      'get': {'operationId': 'getCurrentUser'},
    },
    '/api/api-keys': {
      'get': {
        'operationId': 'listApiKeys',
        'security': [
          {'bearer': <Object?>[]},
        ],
      },
    },
    '/api/library/albums/{id}': {
      'parameters': <Object?>[],
      'get': {'operationId': 'getAlbum'},
      'post': {'operationId': 'touchAlbum', 'security': <Object?>[]},
    },
  },
};

void main() {
  group('anonymousOperations', () {
    test('returns exactly the operations with an empty security requirement, '
        'keyed by method and path template', () {
      expect(anonymousOperations(_spec), {
        'GET /api/health',
        'POST /api/auth/login',
        'POST /api/library/albums/{id}',
      });
    });

    test('an operation without security follows an empty root '
        'requirement', () {
      final spec = {..._spec, 'security': <Object?>[]};
      expect(anonymousOperations(spec), contains('GET /api/auth/me'));
    });
  });

  test('operationIds maps every operation key to its operationId', () {
    expect(operationIds(_spec), {
      'GET /api/health': 'getHealth',
      'POST /api/auth/login': 'login',
      'GET /api/auth/me': 'getCurrentUser',
      'GET /api/api-keys': 'listApiKeys',
      'GET /api/library/albums/{id}': 'getAlbum',
      'POST /api/library/albums/{id}': 'touchAlbum',
    });
  });

  test('renders a Dart library holding both tables', () {
    final source = renderOperations(_spec);
    expect(source, startsWith('// Generated by'));
    expect(source, contains("'GET /api/health',"));
    expect(source, contains("'GET /api/auth/me': 'getCurrentUser',"));
  });

  group('matchOperation', () {
    const keys = {
      'GET /api/library/albums/{id}',
      'GET /api/library/tracks/shuffle',
      'GET /api/library/tracks/{id}',
      'GET /api/health',
    };

    test('a path parameter matches a concrete segment', () {
      expect(
        matchOperation(keys, 'GET', '/api/library/albums/a%2F1'),
        'GET /api/library/albums/{id}',
      );
    });

    test('a literal segment wins over a parameter', () {
      expect(
        matchOperation(keys, 'GET', '/api/library/tracks/shuffle'),
        'GET /api/library/tracks/shuffle',
      );
      expect(
        matchOperation(keys, 'GET', '/api/library/tracks/t1'),
        'GET /api/library/tracks/{id}',
      );
    });

    test('the method, the segment count and empty segments must match', () {
      expect(matchOperation(keys, 'POST', '/api/health'), isNull);
      expect(matchOperation(keys, 'get', '/api/health'), 'GET /api/health');
      expect(matchOperation(keys, 'GET', '/api/library/albums'), isNull);
      expect(matchOperation(keys, 'GET', '/api/library/albums/'), isNull);
      expect(matchOperation(keys, 'GET', '/api/library/albums/a/b'), isNull);
    });
  });
}
